package OOPS.LLD1.Polymorphism;

public class Calculations {

    // add() - Method overloading
    public int add(int a, int b){
        //write a code here
        return a + b;
    }

    public int add(int a, int b, int c){
        //write a code here
        return a + b + c;
    }

    public double add(double a, double b){
        return a + b;
    }

}
